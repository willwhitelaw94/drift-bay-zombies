"""TEAM WORLD build: embed work/world/build/level.glb into work/world/level.js and the lake-side
heightfield into work/world/features/world_terrain.js. meta.js and vendor/ are left as they are.

  /Applications/Blender.app/Contents/MacOS/Blender -b build/house.blend --python zombies/work/world/export_level.py
  uv run --with numpy python zombies/work/world/build_world.py
"""
import base64
import gzip
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
BUILD = HERE / "build"


def main() -> None:
    glb = (BUILD / "level.glb").read_bytes()
    b64 = base64.b64encode(gzip.compress(glb, 9)).decode()
    (HERE / "level.js").write_text(f'export const LEVEL_GZ_B64 = "{b64}";\n')
    t = json.loads((BUILD / "world_terrain.json").read_text())
    z = np.array(t.pop("z_cm"), dtype="<i2")
    t["z_b64"] = base64.b64encode(z.tobytes()).decode()
    (HERE / "features" / "world_terrain.js").write_text(
        "// Generated by build_world.py: the 4 m heightfield (cm, int16 LE, rows = north offset, cols = east offset)\n"
        "// around the house incl. the carved lake bed, plus the jetty placement. Plan metres, z relative to floor.\n"
        "export default " + json.dumps(t, separators=(",", ":")) + ";\n")
    print(f"level.glb {len(glb) / 1e6:.1f} MB -> level.js {len(b64) / 1e6:.1f} MB; terrain {len(t['z_b64']) / 1e3:.0f} kB")


if __name__ == "__main__":
    main()
